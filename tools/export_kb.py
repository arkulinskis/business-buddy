"""Export the knowledge base (theme/assets/bb.js) for the crawlable guide pages: writes server_code/kb_pages.py.

    python -I tools/export_kb.py           rewrite server_code/kb_pages.py from bb.js
    python -I tools/export_kb.py --check   exit 1 if kb_pages.py is stale (tools/check.py runs this)

Node runs bb.js in a sandbox (no browser needed) and hands back the guides, permits, topics and the plan roadmap as
JSON. The guides' HTML snippets (intro, rules, money) are written by us, but they are still cleaned here to a small
allow-list (p, b, strong, i, em, ul, ol, li, br, a href=http(s)) before they land in server code, so the server
pages (server_code/guide_pages.py) can print them as they are. Run it after every content change in bb.js.
"""
import html
import html.parser
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BB_JS = ROOT / "theme" / "assets" / "bb.js"
OUT = ROOT / "server_code" / "kb_pages.py"

NODE = r"""
const fs = require('fs'), vm = require('vm');
const ctx = { window: {}, console: console };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(process.argv[1], 'utf8'), ctx);
const BB = ctx.window.BB;
const out = {
  updated: BB.updated, categories: BB.categories, permits: BB.permits,
  topics: BB.topics.map(t => ({ slug: t.slug, title: t.title, fr: t.fr, summary: t.summary })),
  guides: BB.guides.map(g => Object.assign({}, g, {
    roadmap: BB.planPhases(g, { hiring: false }).map(ph => ({ name: ph.name, blurb: ph.blurb,
      tasks: ph.tasks.map(t => ({ t: t.t, special: !!t.special })) }))
  }))
};
process.stdout.write(JSON.stringify(out));
"""

ALLOWED = {"p", "b", "strong", "i", "em", "ul", "ol", "li", "br", "a"}


class _Clean(html.parser.HTMLParser):
    """Keep only ALLOWED tags (no attributes but a safe href on links); everything else becomes plain text."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out = []

    def handle_starttag(self, tag, attrs):
        if tag not in ALLOWED:
            return
        if tag == "a":
            href = dict(attrs).get("href") or ""
            if href.startswith(("https://", "http://")):
                self.out.append('<a href="%s" rel="noopener">' % html.escape(href, quote=True))
            else:
                self.out.append("<a>")
        elif tag == "br":
            self.out.append("<br>")
        else:
            self.out.append("<%s>" % tag)

    def handle_endtag(self, tag):
        if tag in ALLOWED and tag != "br":
            self.out.append("</%s>" % tag)

    def handle_data(self, data):
        self.out.append(html.escape(data, quote=False))


def clean(fragment):
    p = _Clean()
    p.feed(fragment or "")
    p.close()
    return "".join(p.out).strip()


def export():
    r = subprocess.run(["node", "-e", NODE, str(BB_JS)], capture_output=True, text=True, encoding="utf-8")
    if r.returncode:
        raise SystemExit("node could not read bb.js:\n" + r.stderr)
    kb = json.loads(r.stdout)
    for g in kb["guides"]:
        g["intro"] = clean(g.get("intro"))
        g["money"] = clean(g.get("money"))
        g["rules"] = [[r_[0], clean(r_[1])] for r_ in g.get("rules") or []]
    text = json.dumps(kb, ensure_ascii=False, indent=1, sort_keys=True)
    if "'''" in text or text.endswith("\\"):
        raise SystemExit("bb.js content contains ''' : can't embed it as a raw string")
    return ('"""The knowledge base for the crawlable guide pages (/guides, /guides/<slug>).\n\n'
            "GENERATED by tools/export_kb.py from theme/assets/bb.js: don't edit by hand. tools/check.py fails when it is stale.\n"
            "HTML snippets were cleaned to p/b/strong/i/em/ul/ol/li/br/a.\n"
            '"""\nimport json\n\nKB = json.loads(r\'\'\'' + text + "''')\n")


def main():
    text = export()
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if "--check" in sys.argv:
        if old != text:
            print("server_code/kb_pages.py is stale: run python -I tools/export_kb.py")
            sys.exit(1)
        print("kb_pages.py is current")
        return
    if old != text:
        OUT.write_bytes(text.encode("utf-8"))
        print("wrote server_code/kb_pages.py")
    else:
        print("kb_pages.py already current")


if __name__ == "__main__":
    main()
